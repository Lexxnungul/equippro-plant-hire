/**
 * scripts/convert-tokens.js
 * 
 * Compiles design-tokens.tokens.json into CSS variables following standard
 * two-tier design system architecture:
 *   - Tier 1: Primitives (base palette, DO NOT use directly in UI)
 *   - Tier 2: Color Roles (semantic tokens, USE ONLY THESE in UI)
 *   - Tier 3: Elevations & Typography
 * 
 * Source of truth: design-tokens.tokens.json
 */

const fs = require('fs');
const path = require('path');

// Configuration
const TOKENS_PATH = path.resolve(__dirname, '../design-tokens.tokens.json');
const OUTPUT_PATH = path.resolve(__dirname, '../src/styles/tokens.css');

function toKebab(str) {
  return str
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[\s_]+/g, '-')
    .replace(/[^\w-]/g, '')
    .toLowerCase();
}

function cleanHex(hex) {
  if (typeof hex !== 'string') return hex;
  // If 8-character hex ends with fully opaque 'ff', simplify to 6-character hex
  if (/^#[0-9a-fA-F]{8}$/.test(hex) && hex.toLowerCase().endsWith('ff')) {
    return hex.slice(0, 7).toLowerCase();
  }
  return hex.toLowerCase();
}

function pathToVar(pathArr) {
  return '--' + pathArr.map(toKebab).join('-');
}

function resolveRefToVar(ref) {
  const clean = ref.replace(/^\{|\}$/g, '');
  const parts = clean.split('.');
  const prefix = parts[0] === 'task primitives' ? 'task-primitive' : 'primitive';
  const rest = parts.slice(1);
  return '--' + [prefix, ...rest].map(toKebab).join('-');
}

function buildTokens() {
  if (!fs.existsSync(TOKENS_PATH)) {
    console.error(`Error: Tokens file not found at ${TOKENS_PATH}`);
    process.exit(1);
  }

  const rawData = fs.readFileSync(TOKENS_PATH, 'utf-8');
  const tokens = JSON.parse(rawData);

  const cssLines = [];

  cssLines.push('/**');
  cssLines.push(' * AUTOGENERATED FROM design-tokens.tokens.json - DO NOT EDIT MANUALLY');
  cssLines.push(' * EquipPro Plant Hire Design System');
  cssLines.push(' * Industrial Forge Rust (#9A3412 Tone 40 Primary Anchor)');
  cssLines.push(' */');
  cssLines.push('');
  cssLines.push(':root {');

  // =========================================================================
  // 1. TIER 1: PRIMITIVES (BASE COLOR PALETTES)
  // WARNING: These represent raw color values and MUST NOT be consumed in UI.
  // =========================================================================
  cssLines.push('  /* ========================================================================== */');
  cssLines.push('  /* TIER 1: PRIMITIVE COLOR PALETTES (INTERNAL FOUNDATION)                      */');
  cssLines.push('  /* WARNING: NEVER USE PRIMITIVE VARIABLES DIRECTLY IN UI COMPONENTS.         */');
  cssLines.push('  /* ========================================================================== */');

  const primitiveMap = new Map();

  function extractPrimitives(obj, currentPath = []) {
    for (const [key, val] of Object.entries(obj)) {
      if (val && typeof val === 'object') {
        if (val.type === 'color' && typeof val.value === 'string' && val.value.startsWith('#')) {
          const varName = pathToVar([...currentPath, key]);
          const value = cleanHex(val.value);
          primitiveMap.set(varName, value);
          cssLines.push(`  ${varName}: ${value};`);
        } else {
          extractPrimitives(val, [...currentPath, key]);
        }
      }
    }
  }

  cssLines.push('');
  cssLines.push('  /* --- Task Primitives (EquipPro Industrial Forge Rust System) --- */');
  if (tokens['task primitives']) {
    extractPrimitives(tokens['task primitives'], ['task-primitive']);
  }

  cssLines.push('');
  cssLines.push('  /* --- Core Primitives (Base M3 Fallbacks) --- */');
  if (tokens['primitives']) {
    extractPrimitives(tokens['primitives'], ['primitive']);
  }

  // =========================================================================
  // 2. TIER 2: COLOR ROLES (SEMANTIC TOKENS)
  // CONSUME ONLY THESE IN UI COMPONENTS VIA var(--color-*)
  // =========================================================================
  cssLines.push('');
  cssLines.push('  /* ========================================================================== */');
  cssLines.push('  /* TIER 2: SEMANTIC COLOR ROLES                                              */');
  cssLines.push('  /* MANDATE: USE EXCLUSIVELY THESE VARIABLES IN ALL APPLICATION COMPONENTS.   */');
  cssLines.push('  /* ========================================================================== */');

  const taskRoles = tokens['task color roles'] || {};
  const defaultRoles = tokens['color roles'] || {};

  // Track processed role names to avoid duplicates
  const processedRoles = new Set();

  for (const [roleName, tokenObj] of Object.entries(taskRoles)) {
    const roleKebab = toKebab(roleName);
    const varName = `--color-${roleKebab}`;
    processedRoles.add(roleKebab);

    if (tokenObj.value && tokenObj.value.startsWith('{')) {
      const targetPrimitiveVar = resolveRefToVar(tokenObj.value);
      const fallbackHex = primitiveMap.get(targetPrimitiveVar) || '';
      cssLines.push(`  ${varName}: var(${targetPrimitiveVar}); /* ${fallbackHex} */`);
    } else {
      const hexVal = cleanHex(tokenObj.value);
      cssLines.push(`  ${varName}: ${hexVal};`);
    }
  }

  // Fallback for surface-container if not explicitly in task color roles (mapped to neutral94 / #f2ece7)
  if (!processedRoles.has('surface-container')) {
    const neutral94Var = '--task-primitive-color-palettes-neutral-neutral94';
    if (primitiveMap.has(neutral94Var)) {
      cssLines.push(`  --color-surface-container: var(${neutral94Var}); /* #f2ece7 */`);
    } else {
      cssLines.push(`  --color-surface-container: #f2ece7;`);
    }
    processedRoles.add('surface-container');
  }

  // Append any extra utility roles from default color roles (e.g. background, scrim, shadow)
  cssLines.push('');
  cssLines.push('  /* --- Ancillary Semantic Roles --- */');
  for (const [roleName, tokenObj] of Object.entries(defaultRoles)) {
    const roleKebab = toKebab(roleName);
    if (!processedRoles.has(roleKebab)) {
      const varName = `--color-${roleKebab}`;
      if (tokenObj.value && tokenObj.value.startsWith('{')) {
        const targetPrimitiveVar = resolveRefToVar(tokenObj.value);
        const fallbackHex = primitiveMap.get(targetPrimitiveVar) || '';
        cssLines.push(`  ${varName}: var(${targetPrimitiveVar}); /* ${fallbackHex} */`);
      } else {
        cssLines.push(`  ${varName}: ${cleanHex(tokenObj.value)};`);
      }
      processedRoles.add(roleKebab);
    }
  }

  // =========================================================================
  // 3. TIER 3: ELEVATION & SHADOW TOKENS
  // =========================================================================
  if (tokens['effect']) {
    cssLines.push('');
    cssLines.push('  /* ========================================================================== */');
    cssLines.push('  /* ELEVATION & SHADOW TOKENS                                                  */');
    cssLines.push('  /* ========================================================================== */');
    for (const [shadowName, effectObj] of Object.entries(tokens['effect'])) {
      if (effectObj.type === 'custom-shadow' && effectObj.value) {
        const { offsetX, offsetY, radius, spread, color } = effectObj.value;
        const shadowVar = `--elevation-${toKebab(shadowName)}`;
        cssLines.push(`  ${shadowVar}: ${offsetX}px ${offsetY}px ${radius}px ${spread}px ${color};`);
      }
    }
  }

  // =========================================================================
  // 4. TIER 4: TYPOGRAPHY TOKENS
  // =========================================================================
  if (tokens['typography']) {
    cssLines.push('');
    cssLines.push('  /* ========================================================================== */');
    cssLines.push('  /* TYPOGRAPHY TOKENS                                                          */');
    cssLines.push('  /* ========================================================================== */');
    for (const [styleName, typoObj] of Object.entries(tokens['typography'])) {
      const prefix = `--font-${toKebab(styleName)}`;
      if (typoObj.fontSize?.value) {
        cssLines.push(`  ${prefix}-size: ${typoObj.fontSize.value}px;`);
      }
      if (typoObj.lineHeight?.value) {
        cssLines.push(`  ${prefix}-line-height: ${typoObj.lineHeight.value}px;`);
      }
      if (typoObj.fontWeight?.value) {
        cssLines.push(`  ${prefix}-weight: ${typoObj.fontWeight.value};`);
      }
      if (typoObj.fontFamily?.value) {
        cssLines.push(`  ${prefix}-family: "${typoObj.fontFamily.value}", sans-serif;`);
      }
      if (typoObj.letterSpacing?.value) {
        cssLines.push(`  ${prefix}-tracking: ${typoObj.letterSpacing.value}px;`);
      }
    }
  }

  cssLines.push('}');
  cssLines.push('');

  // Write output
  const outputDir = path.dirname(OUTPUT_PATH);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  fs.writeFileSync(OUTPUT_PATH, cssLines.join('\n'), 'utf-8');
  console.log(`Successfully compiled design tokens to: ${OUTPUT_PATH}`);
  console.log(`Primitives generated: ${primitiveMap.size}`);
  console.log(`Semantic color roles generated: ${processedRoles.size}`);
}

buildTokens();

